/// The widths of every stroke the app draws: outlines, dividers and rules,
/// and the emphasized strokes of progress indicators.
class AppBorderWidth {
  /// Outlines, dividers and rules.
  static const double thin = 1;

  /// Emphasized strokes, such as a progress bar or spinner.
  static const double medium = 2;

  const AppBorderWidth._();
}
