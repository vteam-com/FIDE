import 'dart:io';

import 'package:fide/models/preview_scan.dart';
import 'package:path/path.dart' as p;

/// The files of the preview host in a project's `.dart_tool` folder: the
/// host itself, copied from FIDE's template, and the registry listing the
/// previews of the file shown, which FIDE rewrites for each file.
///
/// They live in the project so the host compiles against the project's
/// own packages and assets, without a `pub get` or a file in its sources.
class PreviewRegistry {
  /// Creates the registry of the project at [projectPath], whose package
  /// is [packageName].
  const PreviewRegistry({required this.projectPath, required this.packageName});

  /// The host's folder, relative to the project.
  static const String folder = '.dart_tool/fide_preview';

  /// The host's entry point, relative to the project, for `flutter run -t`.
  static const String entryPoint = '$folder/main.dart';

  /// The registry's file name, which the host imports.
  static const String _registryFile = 'previews.dart';

  /// The type of a registry entry, as the host reads it.
  static const String _entryType =
      '({String function, int line, Object Function() annotation, '
      'Object? Function() build})';

  /// Prefix of the package URIs of the project's `lib` files.
  static const String _packageScheme = 'package:';

  /// The project's root folder.
  final String projectPath;

  /// The project's package name.
  final String packageName;

  /// The host's folder, absolute.
  String get _hostPath => p.join(projectPath, folder);

  /// Writes the host's entry point from [hostSource].
  Future<void> writeHost(String hostSource) =>
      _write(p.join(projectPath, entryPoint), hostSource);

  /// Writes the registry of the previews [scan] found in [filePath].
  Future<void> writeRegistry(String filePath, PreviewScan scan) =>
      _write(p.join(_hostPath, _registryFile), source(filePath, scan));

  /// Writes a registry listing no preview, so the host renders nothing.
  Future<void> writeEmptyRegistry() =>
      _write(p.join(_hostPath, _registryFile), emptySource);

  /// Writes [content] to the file at absolute [path], creating its folder.
  static Future<void> _write(String path, String content) async {
    final file = File(path);
    await file.parent.create(recursive: true);
    await file.writeAsString(content);
  }

  /// The source of a registry listing no preview.
  static const String emptySource =
      '// Generated by FIDE: no preview is shown.\n'
      '// ignore_for_file: type=lint\n\n'
      'List<$_entryType> fidePreviews() => [];\n';

  /// The registry's source for the previews [scan] found in [filePath]:
  /// it imports the file and the file's own imports, so each annotation
  /// and call compiles as it does in the file, and lists each preview's
  /// annotations and call.
  String source(String filePath, PreviewScan scan) {
    String resolve(String uri) => _uriOf(filePath, uri);
    final buffer = StringBuffer()
      ..writeln(
        '// Generated by FIDE for '
        '${p.relative(filePath, from: projectPath)}; '
        "FIDE rewrites it, don't edit it.",
      )
      ..writeln('// ignore_for_file: type=lint')
      ..writeln()
      ..writeln("import '${_uriOfFile(filePath)}';");
    for (final directive in scan.imports) {
      buffer.writeln(directive.rewritten(resolve));
    }
    buffer
      ..writeln()
      ..writeln('List<$_entryType> fidePreviews() => [');
    for (final preview in scan.previews) {
      for (final annotation in preview.annotations) {
        buffer.writeln(
          "  (function: '${preview.label}', line: ${preview.line}, "
          'annotation: () => ${annotation.constant}, '
          'build: () => ${preview.invocation}),',
        );
      }
    }
    buffer.writeln('];');
    return buffer.toString();
  }

  /// [uri] as imported by [filePath], as the host imports it: a relative
  /// URI becomes the package URI of a `lib` file, else a path relative to
  /// the host; any other URI is kept.
  String _uriOf(String filePath, String uri) {
    if (Uri.parse(uri).hasScheme) return uri;
    final target = p.normalize(
      p.join(p.dirname(filePath), p.fromUri(Uri.parse(uri))),
    );
    return _uriOfFile(target);
  }

  /// How the host imports the file at absolute [path].
  String _uriOfFile(String path) {
    final lib = p.join(projectPath, 'lib');
    if (p.isWithin(lib, path)) {
      final relative = p.split(p.relative(path, from: lib));
      return '$_packageScheme$packageName/${p.url.joinAll(relative)}';
    }
    return p.url.joinAll(p.split(p.relative(path, from: _hostPath)));
  }
}
